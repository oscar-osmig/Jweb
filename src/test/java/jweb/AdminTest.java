package jweb;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@code jweb.Admin} over an H2 table: the index, the list with search and
 * pages, the add and edit forms (the record is the form, the id hidden),
 * validation errors, delete, and the guard.
 */
class AdminTest {

    record Todo(Long id, @Form.Required @Form.Length(min = 3) String title, boolean done) {}

    record Note(String text) {}

    private Sql.Database db;
    private Sql.Table<Todo> todos;
    private JWeb app;

    @BeforeEach
    void schema() {
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:admin;DB_CLOSE_DELAY=-1");
        db = Sql.of(ds);
        db.execute("create table todos (id bigint generated by default as identity primary key, title varchar(255) not null, done boolean not null default false)");
        db.execute("create table notes (text varchar(255))");
        todos = db.table("todos", Todo.class);
        app = JWeb.create();
    }

    @AfterEach
    void drop() {
        db.execute("drop table todos");
        db.execute("drop table notes");
    }

    @Test
    void listsSearchesAddsEditsAndDeletes() {
        Admin admin = Admin.mount(app, "admin/", todos, db.table("notes", Note.class)).title("Back office");
        assertEquals("/admin", admin.path());
        assertEquals(List.of("todos", "notes"), admin.tables());
        todos.insert(new Todo(null, "Write the docs", false));
        todos.insert(new Todo(null, "Ship it", true));
        db.update("insert into notes (text) values (?)", "a note");

        String index = JWebTest.test(app, MockRequest.get("/admin")).getBody();
        JWebTest.assertContains(index, "Back office");
        JWebTest.assertContains(index, "href=\"/admin/todos\"");
        JWebTest.assertContains(index, "2 rows");

        String list = JWebTest.test(app, MockRequest.get("/admin/todos")).getBody();
        JWebTest.assertContains(list, "Write the docs");
        JWebTest.assertContains(list, "Ship it");
        JWebTest.assertContains(list, "href=\"/admin/todos/new\"");
        JWebTest.assertContains(list, "action=\"/admin/todos/1/delete\"");
        JWebTest.assertContains(list, "<th>title</th>");

        String found = JWebTest.test(app, MockRequest.get("/admin/todos").queryParam("q", "ship")).getBody();
        JWebTest.assertContains(found, "Ship it");
        JWebTest.assertNotContains(found, "Write the docs");

        String blank = JWebTest.test(app, MockRequest.get("/admin/todos/new")).getBody();
        JWebTest.assertContains(blank, "action=\"/admin/todos/save\"");
        JWebTest.assertContains(blank, "type=\"hidden\"");
        JWebTest.assertContains(blank, "name=\"title\"");
        JWebTest.assertContains(blank, "type=\"checkbox\"");

        JWebTest.TestResult added = JWebTest.test(app, MockRequest.post("/admin/todos/save")
            .formData(Map.of("id", "", "title", "Review", "done", "true")));
        assertEquals(302, added.getStatus(), added.getBody());
        assertEquals(3, todos.count());
        assertTrue(todos.first("title = ?", "Review").orElseThrow().done());

        JWebTest.TestResult invalid = JWebTest.test(app, MockRequest.post("/admin/todos/save")
            .formData(Map.of("id", "", "title", "no")));
        assertEquals(200, invalid.getStatus());
        JWebTest.assertContains(invalid.getBody(), "jweb-field-invalid");
        JWebTest.assertContains(invalid.getBody(), "value=\"no\"");
        assertEquals(3, todos.count(), "nothing saved");

        String edit = JWebTest.test(app, MockRequest.get("/admin/todos/1")).getBody();
        JWebTest.assertContains(edit, "value=\"1\"");
        JWebTest.assertContains(edit, "value=\"Write the docs\"");
        JWebTest.TestResult edited = JWebTest.test(app, MockRequest.post("/admin/todos/save")
            .formData(Map.of("id", "1", "title", "Write the guide", "done", "true")));
        assertEquals(302, edited.getStatus());
        assertEquals("Write the guide", todos.get(1L).title());
        assertTrue(todos.get(1L).done());
        assertEquals(3, todos.count());

        assertEquals(404, JWebTest.test(app, MockRequest.get("/admin/todos/999")).getStatus());
        assertEquals(404, JWebTest.test(app, MockRequest.get("/admin/nope")).getStatus());

        JWebTest.TestResult deleted = JWebTest.test(app, MockRequest.post("/admin/todos/2/delete"));
        assertEquals(302, deleted.getStatus());
        assertEquals(2, todos.count());
        assertFalse(todos.find(2L).isPresent());

        // a table whose record has no id is read-only
        String notes = JWebTest.test(app, MockRequest.get("/admin/notes")).getBody();
        JWebTest.assertContains(notes, "a note");
        JWebTest.assertNotContains(notes, "/admin/notes/new");
        assertEquals(403, JWebTest.test(app, MockRequest.post("/admin/notes/save").formData(Map.of("text", "x"))).getStatus());
    }

    @Test
    void theGuardStandsInFrontOfEveryAdminRoute() {
        Admin.mount(app, "/admin", todos).guard(Auth.requireRole("admin"));
        assertEquals(401, JWebTest.test(app, MockRequest.get("/admin")).getStatus());
        assertEquals(401, JWebTest.test(app, MockRequest.get("/admin/todos")).getStatus());
        assertEquals(401, JWebTest.test(app, MockRequest.post("/admin/todos/1/delete")).getStatus());

        MockRequest asAdmin = MockRequest.get("/admin/todos");
        Request request = asAdmin.build();
        Auth.login(request, Principal.of("1", "root", "admin"));
        assertEquals(200, JWebTest.test(app, MockRequest.get("/admin/todos").session(request.session())).getStatus());
    }

    @Test
    void tablePagingAndSearchHelpers() {
        for (int i = 1; i <= 7; i++) todos.insert(new Todo(null, "Task " + i + (i % 2 == 0 ? " even" : " odd"), false));
        assertEquals(List.of(1L, 2L, 3L), todos.page(1, 3).stream().map(Todo::id).toList());
        assertEquals(List.of(7L), todos.page(3, 3).stream().map(Todo::id).toList());
        assertEquals(List.of(), todos.page(4, 3));
        assertEquals(3, todos.search("EVEN", 1, 10).size());
        assertEquals(List.of(6L), todos.search("even", 2, 2).stream().map(Todo::id).toList());
        assertEquals(7, todos.search(" ", 1, 10).size());
        assertEquals(List.of("id", "title", "done"), todos.fields());
        assertEquals(Todo.class, todos.type());
        assertTrue(todos.hasId());
        assertEquals(4L, todos.idOf(todos.get(4L)));
        Sql.Table<Note> notes = db.table("notes", Note.class);
        assertFalse(notes.hasId());
        assertEquals(null, notes.idOf(new Note("x")));
    }
}
